practice_modes <- c("Recall", "Guided", "Speed", "Mastery")
mode_notes <- c(
  Recall = "Start with an empty editor and write the operation from memory.",
  Guided = "Study a worked example, then practice on fresh inputs in sequential order.",
  Speed = "Race your target time on each repetition, then check speed alongside accuracy.",
  Mastery = "Build a streak of unaided first passes on new variations. Later reviews test retention."
)

undepRcate_ui <- function() {
  catalog <- exercise_catalog()
  categories <- sort(unique(catalog$category))
  default_category <- catalog$category[match("grouped_summary", catalog$id)]
  brand <- span(class = "brand", span(class = "brand-mark", "R", span("/")), "undepRcate")
  navbarPage(brand, id = "tab", windowTitle = "undepRcate",
    theme = bslib::bs_theme(version = 5, bg = "#121416", fg = "#edf0f2",
                            primary = "#80d5c0", secondary = "#30383b"),
    header = tags$head(tags$meta(name = "theme-color", content = "#121416"),
                       tags$link(rel = "stylesheet", href = "studio.css"),
                       tags$script(src = "studio.js")),
    tabPanel("Practice",
      conditionalPanel("output.active === false", div(class = "shell",
        div(class = "page-heading", h1("Practice studio"),
            p("Choose a skill and build a set of focused repetitions.")),
        uiOutput("finished"),
        div(class = "home-grid",
          div(class = "panel-card setup",
            div(class = "section-head", h2("Build a session"), span(class = "r-mark", ">_")),
            div(class = "form-pair",
              selectInput("category", "Skill category", categories, default_category),
              selectInput("skill", "Drill", setNames(catalog$id, catalog$title), "grouped_summary")),
            div(class = "form-split",
                radioButtons("mode", "Practice mode", practice_modes, "Recall", inline = TRUE),
                textOutput("mode_note", inline = TRUE)),
            div(class = "form-pair",
              selectInput("target", "Repetitions", c("5","10","20","50","100","Unlimited"="0"), "20"),
              selectInput("ordering", "Variation order", c("Sequential", "Randomized"), selectize = FALSE)),
            div(class = "panel-foot", actionButton("start", "Start session  \u2192", class = "btn-primary"))),
          home_insights_ui()))),
      conditionalPanel("output.active === true", div(class = "shell active-shell",
        uiOutput("session_heading"),
        conditionalPanel("output.lesson_pending === true", uiOutput("guided_lesson")),
        conditionalPanel("output.lesson_pending === false",
        div(class = "work-grid",
          div(class = "work-main",
            div(class = "panel-card task-card", h2("Task"), uiOutput("prompt")),
            div(class = "panel-card editor-card",
              div(class = "section-head",
                  h2("Workspace"), radioButtons("source_mode", NULL, c("In-app", "Positron"), inline = TRUE)),
              conditionalPanel("input.source_mode !== 'Positron'",
                shinyAce::aceEditor("code", value = "", mode = "r", theme = "tomorrow_night",
                    height = "248px", fontSize = 15, tabSize = 2, showPrintMargin = FALSE,
                    autoComplete = "disabled", debounce = 200, wordWrap = TRUE)),
              conditionalPanel("input.source_mode === 'Positron'", uiOutput("file_info")),
              div(class = "editor-actions",
                tags$button(id = "check_button", type = "button", class = "btn btn-primary",
                            onclick = "undepRcate.submit()", "Check answer ", tags$kbd("Ctrl \u21b5")),
                tags$button(type = "button", id = "reset_button", class = "btn btn-default", onclick = "undepRcate.reset()",
                            title = "Reset the in-app editor (Alt+Backspace)", "Reset editor"),
                actionButton("advance", "Next repetition \u2192", title = "Next repetition (Alt+Enter)"))),
            div(role = "status", `aria-live` = "polite", uiOutput("feedback"))),
          div(class = "work-side",
            div(class = "panel-card", h2("Inputs"), uiOutput("preview")),
            div(class = "panel-card", h2("Hints"), uiOutput("hint_text"),
                actionButton("hint", "Reveal next hint", class = "hint-button")),
            div(class = "panel-card", h2("Skill progress"), uiOutput("skill_status"))))),
        actionButton("end", "End session", class = "end-session")))),
    tabPanel("Progress", div(class = "shell", analytics_ui(catalog))),
    tabPanel("Settings", div(class = "shell settings",
      div(class = "page-heading", h1("Settings"), p("Preferences are saved on this computer.")),
      div(class = "panel-card", h2("Practice preferences"),
        div(class = "form-pair", numericInput("daily_goal", "Daily repetition goal", 20, 1, 1000),
            numericInput("speed_goal", "Speed target (seconds per repetition)", 90, 5, 3600)),
        selectInput("accent", "Accent palette", c("Sea glass" = "mint", "Glacier" = "blue", "Amber" = "amber")),
        checkboxInput("show_timer", "Show elapsed time in untimed modes", TRUE),
        checkboxInput("disable_suggestions", "Disable in-app editor suggestions", TRUE),
        actionButton("save_prefs", "Save preferences", class = "btn-primary"))))
  )
}
