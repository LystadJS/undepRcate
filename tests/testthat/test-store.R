testthat::test_that("Guided lessons persist separately from attempts, timing, repetitions and hints", {
  path <- tempfile(fileext = ".sqlite")
  con <- db_open(path)
  lesson <- start_session(con, "summary", "Guided", "Randomized", 2L, "summary", 1L, now = 100)
  testthat::expect_identical(lesson$ordering, "Sequential")
  testthat::expect_identical(lesson$lesson_pending, 1L)
  testthat::expect_identical(lesson$position, 1L)
  testthat::expect_identical(lesson$hints, 0L)
  db_close(con)
  con <- db_open(path)
  other <- db_open(path)
  withr::defer({ db_close(con); db_close(other); unlink(path) })
  testthat::expect_identical(active_session(con), lesson)
  testthat::expect_error(save_draft(con, lesson, "draft", 2L), "Finish the Guided lesson")
  testthat::expect_error(record_attempt(con, lesson, "answer", 0L, "pass", 1), "Finish the Guided lesson")
  testthat::expect_error(advance_session(con, lesson), "Finish the Guided lesson")
  testthat::expect_identical(active_session(con), lesson)
  s <- finish_guided_lesson(other, lesson, now = 730)
  testthat::expect_identical(active_session(con), s)
  testthat::expect_identical(s$lesson_pending, 0L)
  testthat::expect_identical(s$item_started_at, 730)
  testthat::expect_identical(s$started_at, 100)
  testthat::expect_identical(s$position, 1L)
  testthat::expect_identical(s$hints, 0L)
  testthat::expect_equal(nrow(attempt_history(con)), 0L)
  testthat::expect_identical(finish_guided_lesson(con, s, now = 1000), s)
  testthat::expect_identical(finish_guided_lesson(con, lesson, now = 1100), s)
  testthat::expect_error(save_draft(con, lesson, "late edit"), "another tab")
  testthat::expect_error(record_attempt(con, lesson, "late submission", 0L, "pass", 1), "another tab")
  testthat::expect_error(advance_session(con, lesson), "another tab")
  s <- save_draft(con, s, "answer", 3L)
  testthat::expect_error(finish_guided_lesson(con, lesson), "another tab")
  s <- record_attempt(con, s, "answer", 0L, "pass", 6)
  s <- advance_session(con, s, "summary", 2L)
  testthat::expect_identical(s$hints, 0L)
  testthat::expect_identical(s$lesson_pending, 0L)
  s <- record_attempt(con, s, "answer", 0L, "pass", 5)
  testthat::expect_identical(attempt_history(con)$hints, c(3L, 0L))
  testthat::expect_equal(skill_progress(con)$unseen_successes, 1L)
  testthat::expect_null(advance_session(con, s))
})

testthat::test_that("opening a version-one database preserves progress while adding mastery indexes", {
  path <- tempfile(fileext = ".sqlite")
  con <- db_open(path)
  s <- start_session(con, "summary", "Recall", "Sequential", 5L, "summary", 21L)
  s <- record_attempt(con, s, "df", 0, "pass", 10)
  DBI::dbExecute(con, "DROP INDEX mastery_session_items")
  DBI::dbExecute(con, "DROP INDEX mastery_seed_history")
  DBI::dbExecute(con, "ALTER TABLE sessions DROP COLUMN lesson_pending")
  DBI::dbExecute(con, "PRAGMA user_version=1")
  db_close(con)
  con <- db_open(path)
  withr::defer({ db_close(con); unlink(path) })
  testthat::expect_equal(DBI::dbGetQuery(con, "PRAGMA user_version")[[1L]], 3L)
  testthat::expect_equal(active_session(con), s)
  testthat::expect_equal(attempt_history(con)$code, "df")
})

testthat::test_that("legacy active Guided practice keeps its position, draft, clock, hints and attempts", {
  path <- tempfile(fileext = ".sqlite")
  con <- db_open(path)
  s <- start_session(con, "summary", "Guided", "Sequential", 20L, "summary", 15L, now = 100)
  s <- finish_guided_lesson(con, s, now = 110)
  s <- record_attempt(con, s, "answer", 2L, "pass", 5, now = 115)
  s <- advance_session(con, s, "summary", 16L, now = 120)
  s <- save_draft(con, s, "partial", 1L)
  history <- attempt_history(con)
  DBI::dbExecute(con, "ALTER TABLE sessions DROP COLUMN lesson_pending")
  DBI::dbExecute(con, "UPDATE sessions SET ordering='Randomized'")
  DBI::dbExecute(con, "PRAGMA user_version=2")
  db_close(con)
  con <- db_open(path)
  withr::defer({ db_close(con); unlink(path) })
  resumed <- active_session(con)
  testthat::expect_identical(resumed$lesson_pending, 0L)
  testthat::expect_identical(resumed$ordering, "Sequential")
  testthat::expect_gt(resumed$revision, s$revision)
  testthat::expect_identical(resumed$draft, "partial")
  testthat::expect_identical(resumed$position, 2L)
  testthat::expect_identical(resumed$seed, 16L)
  testthat::expect_identical(resumed$hints, 1L)
  testthat::expect_identical(resumed$item_started_at, 120)
  testthat::expect_identical(attempt_history(con), history)
})

testthat::test_that("other modes stay in practice and a learner can leave during a lesson", {
  con <- db_open(":memory:")
  withr::defer(db_close(con))
  s <- start_session(con, "summary", "Guided", "Randomized", 5, "summary", 1)
  testthat::expect_null(end_session(con, s))
  testthat::expect_equal(nrow(attempt_history(con)), 0)
  for (mode in c("Recall", "Speed", "Mastery")) {
    s <- start_session(con, "summary", mode, "Randomized", 5, "summary", 1)
    testthat::expect_identical(s$lesson_pending, 0L)
    testthat::expect_identical(s$ordering, "Randomized")
    testthat::expect_error(finish_guided_lesson(con, s), "Only Guided")
    end_session(con, s)
  }
})
