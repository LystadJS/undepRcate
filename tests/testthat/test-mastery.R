testthat::test_that("mastery checkpoints count first-pass independent variations in one drill and session", {
  con <- db_open(":memory:")
  withr::defer(db_close(con))
  prior <- start_session(con, "summary", "Guided", "Sequential", 1L, "summary", 10L)
  prior <- finish_guided_lesson(con, prior)
  prior <- record_attempt(con, prior, "a", 0, "pass", 1, guide_shown = TRUE)
  advance_session(con, prior)
  testthat::expect_equal(mastery_checkpoint(con, prior$id, "summary"), list(current = 0L, best = 0L))
  s <- start_session(con, "summary", "Mastery", "Sequential", 0L, "summary", 11L)
  checkpoint <- function() mastery_checkpoint(con, s$id, "summary")
  submit <- function(row, status = "pass") record_attempt(con, row, "code", row$hints, status, 1)
  s <- submit(s)
  s <- submit(advance_session(con, s, "summary", 10L, 2L))
  testthat::expect_equal(checkpoint(), list(current = 1L, best = 1L))
  s <- submit(advance_session(con, s, "other", 12L))
  testthat::expect_equal(checkpoint(), list(current = 1L, best = 1L))
  s <- submit(advance_session(con, s, "summary", 12L), "infrastructure_error")
  s <- submit(s)
  testthat::expect_equal(checkpoint(), list(current = 2L, best = 2L))
  s <- submit(advance_session(con, s, "summary", 13L), "incorrect")
  testthat::expect_equal(checkpoint(), list(current = 0L, best = 2L))
  s <- submit(s)
  testthat::expect_equal(checkpoint(), list(current = 0L, best = 2L))
  s <- submit(advance_session(con, s, "summary", 14L))
  testthat::expect_equal(checkpoint(), list(current = 1L, best = 2L))
  s <- advance_session(con, s, "summary", 15L)
  s <- save_draft(con, s, "", 1L)
  testthat::expect_equal(checkpoint(), list(current = 0L, best = 2L))
  s <- submit(s)
  end_session(con, s)
  testthat::expect_equal(checkpoint(), list(current = 0L, best = 2L))
})
