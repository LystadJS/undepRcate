testthat::test_that("sessions, drafts, attempts and settings survive a database reopen", {
  path <- tempfile(fileext = ".sqlite")
  con <- db_open(path)
  s <- start_session(con, "grouped_summary", "Recall", "Sequential", 2, "grouped_summary", 42)
  s <- save_draft(con, s, "summary(df)", 1L)
  set_setting(con, "goal", 25)
  db_close(con)
  con <- db_open(path)
  withr::defer({ db_close(con); unlink(path) })
  testthat::expect_equal(active_session(con), s)
  testthat::expect_identical(get_setting(con, "goal"), "25")
  s <- record_attempt(con, s, "oops", 0, "runtime_error", 8)
  testthat::expect_error(advance_session(con, s), "Pass this repetition")
  s <- record_attempt(con, s, "df", 1, "pass", 12)
  testthat::expect_equal(s$passed, 1L)
  testthat::expect_error(save_draft(con, s, "different"), "already passed")
  testthat::expect_error(record_attempt(con, s, "df", 1, "pass", 12), "already passed")
  s <- advance_session(con, s, "grouped_summary", 43, 2L)
  testthat::expect_equal(s$position, 2L)
  testthat::expect_equal(s$hints, 0L)
  testthat::expect_identical(s$draft, "")
  s <- record_attempt(con, s, "df", 0, "pass", 10)
  testthat::expect_null(advance_session(con, s))
  testthat::expect_null(active_session(con))
  h <- attempt_history(con)
  testthat::expect_equal(h$position, c(1L, 1L, 2L))
  testthat::expect_equal(h$hints, c(1L, 1L, 0L))
  testthat::expect_equal(h$status, c("runtime_error", "pass", "pass"))
  testthat::expect_false("code" %in% names(attempt_history(con, include_code = FALSE)))
  testthat::expect_identical(recent_answer_code(con, h$id[c(3, 1)]), c("df", "oops"))
  testthat::expect_equal(skill_progress(con)$unseen_successes, 1)
})

testthat::test_that("two app connections cannot overwrite each other's changes", {
  path <- tempfile(fileext = ".sqlite")
  a <- db_open(path)
  b <- db_open(path)
  withr::defer({ db_close(a); db_close(b); unlink(path) })
  stale <- start_session(a, "fundamentals", "Recall", "Random", 0, "vec", 10)
  testthat::expect_error(start_session(b, "all", "Recall", "Random", 5, "vec", 9), "current practice")
  fresh <- save_draft(a, stale, "one", 2)
  testthat::expect_error(record_attempt(b, stale, "two", 0, "pass", 1), "another tab")
  testthat::expect_error(save_draft(b, stale, "two"), "another tab")
  testthat::expect_error(end_session(b, stale), "another tab")
  testthat::expect_equal(nrow(attempt_history(b)), 0L)
  testthat::expect_identical(active_session(b)$draft, "one")
  # Failed attempt INSERT rolls back the earlier revision change in its transaction.
  testthat::expect_error(record_attempt(a, fresh, "oops", 2, "unknown", 1))
  testthat::expect_equal(active_session(a), fresh)
  fresh <- record_attempt(a, fresh, "one", 2, "pass", 2)
  fresh <- advance_session(a, fresh, "vec", 11, 1L)
  testthat::expect_equal(fresh$position, 2L)
  testthat::expect_null(end_session(a, fresh))
})

